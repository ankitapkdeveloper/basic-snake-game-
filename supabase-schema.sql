create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null default 'Player',
  avatar_url text not null default '🐍',
  coins integer not null default 100 check (coins >= 0),
  high_score integer not null default 0 check (high_score >= 0),
  games_played integer not null default 0 check (games_played >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  avatar_url text not null default '🐍',
  score integer not null check (score >= 0),
  created_at timestamptz not null default now()
);

create index if not exists leaderboard_score_idx on public.leaderboard(score desc);
create index if not exists leaderboard_user_idx on public.leaderboard(user_id);

alter table public.profiles enable row level security;
alter table public.leaderboard enable row level security;

revoke all on table public.profiles from anon;
revoke all on table public.leaderboard from anon;
grant select, insert, update on public.profiles to authenticated;
grant select on public.leaderboard to anon, authenticated;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for select to authenticated
using ((select auth.uid()) = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles for insert to authenticated
with check ((select auth.uid()) = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles for update to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

drop policy if exists "leaderboard_public_read" on public.leaderboard;
create policy "leaderboard_public_read" on public.leaderboard for select to anon, authenticated
using (true);

-- Only let signed-in users insert a row for themselves.
