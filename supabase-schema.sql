-- Atomic score submission + reward function for the prototype.
-- It keeps the browser from directly changing the user's coins/high score.
create or replace function public.submit_snake_score(p_score integer)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  p public.profiles;
  reward integer := greatest(0, floor(p_score / 10));
begin
  if uid is null then
    raise exception 'Login required';
  end if;

  if p_score < 0 or p_score > 100000 then
    raise exception 'Invalid score';
  end if;

  select * into p from public.profiles where id = uid for update;

  if not found then
    insert into public.profiles(id, username, avatar_url, coins, high_score, games_played)
    values (uid, coalesce((select raw_user_meta_data->>'username' from auth.users where id=uid), 'Player'), '🐍', 100, 0, 0)
    returning * into p;
  end if;

  update public.profiles
  set coins = coins + reward,
      high_score = greatest(high_score, p_score),
      games_played = games_played + 1,
      updated_at = now()
  where id = uid;

  insert into public.leaderboard(user_id, username, avatar_url, score)
  values (uid, p.username, p.avatar_url, p_score);

  return json_build_object('score', p_score, 'reward', reward);
end;
$$;

revoke all on function public.submit_snake_score(integer) from public, anon;
grant execute on function public.submit_snake_score(integer) to authenticated;

-- Keep updated_at fresh on profile edits.
create or replace function public.set_profile_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at
before update on public.profiles
for each row execute function public.set_profile_updated_at();

